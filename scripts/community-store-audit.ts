import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { auditStore, auditProposal, admit, auditHash, auditHashBytes, fixtureGithub, AUDIT_REPOSITORY_ID, AUDIT_RULES } from './community-audit-fixtures';
import { createCommunityService } from '../src/service/community/service';
for (const kind of ['file', 'd1'] as const) {
  const { store } = await auditStore(kind);
  const proposal = auditProposal();
  const github = fixtureGithub(proposal);
  const service = createCommunityService({ store, github, repositoryId: AUDIT_REPOSITORY_ID, authenticate: async authorization => authorization ? { id: authorization, displayName: 'audit', createdAt: 0 } : null, linkedProvider: async id => id === 'moderator', moderators: ['moderator', 'guest-moderator'], now: Date.now, hash: auditHash, hashBytes: auditHashBytes, randomId: randomUUID, rulesRevision: AUDIT_RULES, contentApiVersion: 1, readiness: null, pointsEnabled: false });
  const call = (path: string, authorization: string | null = null, input?: unknown) => service.handle({ method: input === undefined ? 'GET' : 'POST', path: path.split('?')[0]!, url: new URL(`https://audit.invalid${path}`), authorization, body: input === undefined ? '' : JSON.stringify(input) });
  assert.equal((await call('/community/me')).status, 401);
  assert.equal((await call('/community/proposals?limit=51')).status, 400);
  assert.equal((await call('/community/proposals?cursor=-1')).status, 400);
  assert.equal((await call('/community/import', 'viewer', { url: proposal.sourceUrl })).status, 200);
  const review = { number: 1, headSha: proposal.headSha, expectedRevision: 0, decision: 'open', operationId: 'review-operation-1', note: 'private reviewer note' };
  assert.equal((await call('/community/moderation/review', 'viewer', review)).status, 403);
  assert.equal((await call('/community/moderation/review', 'guest-moderator', review)).status, 403);
  assert.equal((await call('/community/moderation/review', 'moderator', review)).status, 200);
  assert.equal((await call('/community/moderation/review', 'moderator', review)).status, 200);
  assert.equal((await call('/community/moderation/review', 'moderator', { ...review, operationId: 'review-operation-2' })).status, 409);
  assert.equal((await call('/community/moderation/review', 'moderator', { ...review, expectedRevision: 1, operationId: 'review-operation-3', technicalReady: true, technicalEvidence: { fightOnOff: 'Actual fight ON/OFF evidence reference', determinism: 'Actual byte-identical log evidence reference', pairedUi: 'Actual desktop/mobile capture reference', keywordSurfaces: 'Actual text face/details/token reference' } })).status, 409);
  const publicListing = await call('/community/proposals');
  assert.equal(publicListing.status, 200);
  assert(!JSON.stringify(publicListing.body).includes('private reviewer note'));
  assert(!JSON.stringify(publicListing.body).includes('moderatorId'));
  assert(JSON.stringify(publicListing.body).includes('<script>literal proposal</script>'));
  assert.equal((await call('/community/me', 'viewer')).status, 200);
  assert.equal(((await call('/community/me', 'viewer')).body as { canModerate: boolean }).canModerate, false);
  assert.equal(((await call('/community/me', 'guest-moderator')).body as { canModerate: boolean }).canModerate, false);
  assert.equal(((await call('/community/me', 'moderator')).body as { canModerate: boolean }).canModerate, true);
  assert.equal((await store.wallet('viewer')).balance, 0);
  assert.equal((await call('/community/upload', 'viewer', {})).status, 404);
  assert.equal((await call('/community/publish', 'viewer', {})).status, 404);
  assert.equal((await call('/community/grant', 'viewer', {})).status, 404);
  for (let n = 2; n <= 4; n++) await admit(store, auditProposal(n));
  assert.equal((await store.listProposals(1, 2, 'newest')).length, 2);
  assert.equal((await store.getProposal(proposal.key))!.state, 'open');
  const moved = { ...proposal, headSha: 'd'.repeat(40) };
  await store.importProposal(moved, []);
  assert.equal((await store.getProposal(proposal.key))!.state, 'pending_review');
  assert.equal((await store.getProposal(proposal.key))!.reviewedHeadSha, null);
  assert.equal((await store.getProposal(proposal.key))!.technical, null);
  console.log(`OK community-store ${kind}: auth/privacy/moderation/replay/pagination/head-reset/no-publisher`);
}
